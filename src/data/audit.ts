export function auditFunnelRows(fixed: ReadonlySet<number>) {
  let visitors = 1000;
  const rows = auditStages.map((stage, index) => {
    const before = visitors;
    const rate = fixed.has(index) ? stage.fix : stage.keep;
    visitors *= rate;
    return {
      index,
      before,
      now: visitors,
      keepPct: (visitors / 1000) * 100,
      lostPct: ((before - visitors) / 1000) * 100,
      fixed: fixed.has(index),
    };
  });
  const base = auditStages.reduce((total, stage) => total * stage.keep, 1000);
  return { rows, arrived: visitors, base };
}

export function formatAudit(value: number) {
  return value.toFixed(1).replace(".", ",");
}
