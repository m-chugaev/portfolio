export function getServiceById(id: string): Service | undefined {
  return services.find((service) => service.id === id);
}

export function getOtherServices(id: string): Service[] {
  return services.filter((service) => service.id !== id);
}

export function getServicesForProject(projectId: string): Service[] {
  return services.filter((service) =>
    service.relatedCases.some((item) => item.projectId === projectId),
  );
}
