export function quizModel(input: { traffic?: string; goal?: string; questions: number }) {
  const startRate =
    { social: 0.2, direct: 0.18, search: 0.11, word: 0.16 }[input.traffic ?? ""] ?? 0.16;
  const formRate =
    { social: 0.012, direct: 0.018, search: 0.032, word: 0.035 }[input.traffic ?? ""] ?? 0.02;
  const contactRate = { calc: 0.36, pick: 0.33, book: 0.3, lead: 0.24 }[input.goal ?? ""] ?? 0.3;
  const steps: Array<{ label: string; value: number; last?: boolean }> = [
    { label: "визиты", value: 1000 },
    { label: "вопрос 1", value: 1000 * startRate },
  ];
  let value = 1000 * startRate;

  for (let index = 2; index <= input.questions; index += 1) {
    value *= Math.max(0.7, 0.92 - 0.03 * (index - 2));
    steps.push({ label: `вопрос ${index}`, value });
  }

  value *= contactRate;
  steps.push({ label: "контакт", value, last: true });

  return { steps, form: 1000 * formRate, start: 1000 * startRate, quiz: value };
}

